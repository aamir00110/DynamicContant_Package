CREATE SEQUENCE MS_PM_PLAN_NO_SEQ START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE MS_PM_SCHEDULE_NO_SEQ START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE MS_PM_WO_NO_SEQ START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;

CREATE OR REPLACE TRIGGER MS_PM_PLAN_H_BI
BEFORE INSERT ON MS_PM_PLAN_H
FOR EACH ROW
DECLARE
  l_user VARCHAR2(100);
BEGIN
  l_user := NVL(SYS_CONTEXT('APEX$SESSION','APP_USER'), USER);
  IF :NEW.PLAN_NO IS NULL THEN
    :NEW.PLAN_NO := 'PM-' || TO_CHAR(SYSDATE,'YYYY') || '-' ||
                    LPAD(MS_PM_PLAN_NO_SEQ.NEXTVAL,6,'0');
  END IF;
  IF :NEW.CREATED_DATE IS NULL THEN :NEW.CREATED_DATE := SYSDATE; END IF;
  IF :NEW.CREATED_BY IS NULL THEN :NEW.CREATED_BY := l_user; END IF;
END;
/

CREATE OR REPLACE TRIGGER MS_PM_PLAN_H_BU
BEFORE UPDATE ON MS_PM_PLAN_H
FOR EACH ROW
BEGIN
  :NEW.UPDATED_DATE := SYSDATE;
  :NEW.UPDATED_BY := NVL(SYS_CONTEXT('APEX$SESSION','APP_USER'), USER);
END;
/

