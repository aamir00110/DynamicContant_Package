-- ---------------------------------------------------------------------------
-- 13. Package body
-- ---------------------------------------------------------------------------
CREATE OR REPLACE PACKAGE BODY MS_PM_PKG AS

  FUNCTION MS_CURRENT_USER RETURN VARCHAR2 IS
  BEGIN
    RETURN NVL(SYS_CONTEXT('APEX$SESSION','APP_USER'), USER);
  END;

  FUNCTION NEXT_DATE(
    P_BASE_DATE IN DATE,
    P_FREQUENCY_ID IN NUMBER,
    P_CUSTOM_DAYS IN NUMBER
  ) RETURN DATE IS
    l_code VARCHAR2(30);
    l_days NUMBER;
    l_months NUMBER;
  BEGIN
    SELECT FREQUENCY_CODE, INTERVAL_DAYS, INTERVAL_MONTHS
      INTO l_code, l_days, l_months
      FROM MS_PM_FREQUENCY
     WHERE FREQUENCY_ID = P_FREQUENCY_ID
       AND ACTIVE_YN = 'Y';

    IF l_code = 'CUSTOM' THEN
      IF NVL(P_CUSTOM_DAYS,0) <= 0 THEN
        RAISE_APPLICATION_ERROR(-20010,'Custom interval days must be greater than zero.');
      END IF;
      RETURN TRUNC(P_BASE_DATE) + P_CUSTOM_DAYS;
    ELSIF l_days IS NOT NULL THEN
      RETURN TRUNC(P_BASE_DATE) + l_days;
    ELSE
      RETURN ADD_MONTHS(TRUNC(P_BASE_DATE),l_months);
    END IF;
  END NEXT_DATE;

  FUNCTION GET_STOCK_QTY(P_ITEM_ID IN NUMBER) RETURN NUMBER IS
    l_qty NUMBER;
  BEGIN
    SELECT NVL(SUM(
      CASE
        WHEN TXN_TYPE IN ('OPENING','RECEIPT','ADJUST_IN') THEN QUANTITY
        WHEN TXN_TYPE IN ('ISSUE','ADJUST_OUT') THEN -QUANTITY
        ELSE 0
      END),0)
      INTO l_qty
      FROM MS_PM_STOCK_TXN
     WHERE ITEM_ID = P_ITEM_ID;
    RETURN l_qty;
  END GET_STOCK_QTY;

  PROCEDURE GENERATE_SCHEDULE(
    P_PLAN_ID IN NUMBER,
    P_UNTIL_DATE IN DATE
  ) IS
    l_start DATE;
    l_end DATE;
    l_next DATE;
    l_frequency_id NUMBER;
    l_custom_days NUMBER;
    l_status VARCHAR2(20);
    l_count NUMBER := 0;
  BEGIN
    IF P_UNTIL_DATE IS NULL THEN
      RAISE_APPLICATION_ERROR(-20011,'Schedule horizon date is required.');
    END IF;

    SELECT TRUNC(START_DATE), END_DATE, FREQUENCY_ID,
           CUSTOM_INTERVAL_DAYS, STATUS_CODE
      INTO l_start,l_end,l_frequency_id,l_custom_days,l_status
      FROM MS_PM_PLAN_H
     WHERE PLAN_ID = P_PLAN_ID
       AND ACTIVE_YN = 'Y';

    IF l_status <> 'ACTIVE' THEN
      RAISE_APPLICATION_ERROR(-20012,'Only ACTIVE plans can generate schedules.');
    END IF;

    l_next := l_start;

    WHILE l_next <= TRUNC(P_UNTIL_DATE)
      AND (l_end IS NULL OR l_next <= TRUNC(l_end))
    LOOP
      BEGIN
        INSERT INTO MS_PM_SCHEDULE
          (PLAN_ID,SCHEDULE_DATE,DUE_DATE,STATUS_CODE,GENERATED_YN)
        VALUES
          (P_PLAN_ID,l_next,l_next,'PENDING','Y');
        l_count := l_count + 1;
      EXCEPTION
        WHEN DUP_VAL_ON_INDEX THEN NULL;
      END;

      l_next := NEXT_DATE(l_next,l_frequency_id,l_custom_days);
      IF l_count > 5000 THEN
        RAISE_APPLICATION_ERROR(-20013,'Schedule generation limit exceeded.');
      END IF;
    END LOOP;

    UPDATE MS_PM_PLAN_H
       SET NEXT_DUE_DATE =
         (SELECT MIN(S.DUE_DATE)
            FROM MS_PM_SCHEDULE S
           WHERE S.PLAN_ID = P_PLAN_ID
             AND S.STATUS_CODE IN ('PENDING','OVERDUE'))
     WHERE PLAN_ID = P_PLAN_ID;
  END GENERATE_SCHEDULE;

  PROCEDURE GENERATE_WORK_ORDERS(P_THROUGH_DATE IN DATE) IS
    l_wo_id NUMBER;
    l_plan_id NUMBER;
    l_machine_id NUMBER;
    l_hall_id NUMBER;
    l_line_id NUMBER;
    l_assigned_to VARCHAR2(100);
    l_priority VARCHAR2(20);
  BEGIN
    FOR r IN (
      SELECT S.SCHEDULE_ID,S.PLAN_ID,S.DUE_DATE,
             P.MACHINE_ID,P.HALL_ID,P.LINE_ID,P.ASSIGNED_TO,P.PRIORITY
        FROM MS_PM_SCHEDULE S
        JOIN MS_PM_PLAN_H P ON P.PLAN_ID = S.PLAN_ID
       WHERE S.STATUS_CODE IN ('PENDING','OVERDUE')
         AND S.DUE_DATE <= TRUNC(P_THROUGH_DATE)
         AND P.STATUS_CODE = 'ACTIVE'
         AND P.ACTIVE_YN = 'Y'
       ORDER BY S.DUE_DATE,S.SCHEDULE_ID
    ) LOOP
      BEGIN
        INSERT INTO MS_PM_WORK_ORDER
          (SCHEDULE_ID,PLAN_ID,MACHINE_ID,HALL_ID,LINE_ID,
           ASSIGNED_TO,TARGET_DATE,PRIORITY,STATUS_CODE)
        VALUES
          (r.SCHEDULE_ID,r.PLAN_ID,r.MACHINE_ID,r.HALL_ID,r.LINE_ID,
           r.ASSIGNED_TO,r.DUE_DATE,r.PRIORITY,
           CASE WHEN r.ASSIGNED_TO IS NULL THEN 'OPEN' ELSE 'ASSIGNED' END)
        RETURNING WORK_ORDER_ID INTO l_wo_id;

        INSERT INTO MS_PM_WO_TASK_D
          (WORK_ORDER_ID,PLAN_D_ID,TASK_ID,SEQUENCE_NO,MANDATORY_YN)
        SELECT l_wo_id,D.PLAN_D_ID,D.TASK_ID,D.SEQUENCE_NO,D.MANDATORY_YN
          FROM MS_PM_PLAN_D D
          JOIN MS_PM_TASK_M T ON T.TASK_ID = D.TASK_ID
         WHERE D.PLAN_ID = r.PLAN_ID
           AND T.ACTIVE_YN = 'Y';

        UPDATE MS_PM_SCHEDULE
           SET STATUS_CODE = 'GENERATED',UPDATED_DATE = SYSDATE,
               UPDATED_BY = MS_CURRENT_USER()
         WHERE SCHEDULE_ID = r.SCHEDULE_ID;

      EXCEPTION
        WHEN DUP_VAL_ON_INDEX THEN
          -- Existing work order for this schedule: keep processing idempotent.
          UPDATE MS_PM_SCHEDULE
             SET STATUS_CODE = 'GENERATED'
           WHERE SCHEDULE_ID = r.SCHEDULE_ID
             AND STATUS_CODE IN ('PENDING','OVERDUE');
      END;
    END LOOP;
  END GENERATE_WORK_ORDERS;

  PROCEDURE START_WORK_ORDER(P_WORK_ORDER_ID IN NUMBER) IS
    l_status VARCHAR2(25);
  BEGIN
    SELECT STATUS_CODE INTO l_status
      FROM MS_PM_WORK_ORDER
     WHERE WORK_ORDER_ID = P_WORK_ORDER_ID
     FOR UPDATE;

    IF l_status NOT IN ('OPEN','ASSIGNED','REJECTED','WAITING_PARTS') THEN
      RAISE_APPLICATION_ERROR(-20014,'Work order cannot be started from status '||l_status);
    END IF;

    UPDATE MS_PM_WORK_ORDER
       SET STATUS_CODE = 'IN_PROGRESS',
           START_DATE_TIME = NVL(START_DATE_TIME,SYSDATE)
     WHERE WORK_ORDER_ID = P_WORK_ORDER_ID;

    UPDATE MS_PM_SCHEDULE
       SET STATUS_CODE = 'IN_PROGRESS'
     WHERE SCHEDULE_ID =
       (SELECT SCHEDULE_ID FROM MS_PM_WORK_ORDER
         WHERE WORK_ORDER_ID = P_WORK_ORDER_ID);
  END START_WORK_ORDER;

  PROCEDURE SET_TASK_RESULT(
    P_WO_TASK_ID IN NUMBER,
    P_RESULT_CODE IN VARCHAR2,
    P_REMARKS IN VARCHAR2 DEFAULT NULL
  ) IS
    l_status VARCHAR2(20);
  BEGIN
    IF P_RESULT_CODE NOT IN ('OK','NOT_OK','NOT_APPLICABLE','PENDING') THEN
      RAISE_APPLICATION_ERROR(-20015,'Invalid checklist result.');
    END IF;

    SELECT W.STATUS_CODE INTO l_status
      FROM MS_PM_WO_TASK_D D
      JOIN MS_PM_WORK_ORDER W ON W.WORK_ORDER_ID = D.WORK_ORDER_ID
     WHERE D.WO_TASK_ID = P_WO_TASK_ID;

    IF l_status <> 'IN_PROGRESS' THEN
      RAISE_APPLICATION_ERROR(-20016,'Checklist can only be updated while work order is IN_PROGRESS.');
    END IF;

    UPDATE MS_PM_WO_TASK_D
       SET RESULT_CODE = P_RESULT_CODE,
           TASK_REMARKS = P_REMARKS,
           COMPLETED_BY = CASE WHEN P_RESULT_CODE = 'PENDING' THEN NULL ELSE MS_CURRENT_USER END,
           COMPLETED_DATE = CASE WHEN P_RESULT_CODE = 'PENDING' THEN NULL ELSE SYSDATE END
     WHERE WO_TASK_ID = P_WO_TASK_ID;
  END SET_TASK_RESULT;

  PROCEDURE COMPLETE_WORK_ORDER(
    P_WORK_ORDER_ID IN NUMBER,
    P_WORK_REMARKS IN VARCHAR2 DEFAULT NULL
  ) IS
    l_status VARCHAR2(25);
    l_missing NUMBER;
  BEGIN
    SELECT STATUS_CODE INTO l_status
      FROM MS_PM_WORK_ORDER
     WHERE WORK_ORDER_ID = P_WORK_ORDER_ID
     FOR UPDATE;

    IF l_status <> 'IN_PROGRESS' THEN
      RAISE_APPLICATION_ERROR(-20017,'Only IN_PROGRESS work orders can be submitted.');
    END IF;

    SELECT COUNT(*) INTO l_missing
      FROM MS_PM_WO_TASK_D
     WHERE WORK_ORDER_ID = P_WORK_ORDER_ID
       AND MANDATORY_YN = 'Y'
       AND RESULT_CODE = 'PENDING';

    IF l_missing > 0 THEN
      RAISE_APPLICATION_ERROR(-20018,'Complete all mandatory checklist tasks before submission.');
    END IF;

    UPDATE MS_PM_WORK_ORDER
       SET STATUS_CODE = 'PENDING_APPROVAL',
           COMPLETED_DATE_TIME = SYSDATE,
           WORK_REMARKS = P_WORK_REMARKS
     WHERE WORK_ORDER_ID = P_WORK_ORDER_ID;

    MERGE INTO MS_PM_APPROVAL A
    USING (SELECT P_WORK_ORDER_ID WORK_ORDER_ID FROM DUAL) X
       ON (A.WORK_ORDER_ID = X.WORK_ORDER_ID AND A.APPROVAL_LEVEL = 1)
    WHEN MATCHED THEN UPDATE SET
      APPROVAL_STATUS = 'PENDING',
      APPROVAL_DATE = NULL,
      APPROVAL_REMARKS = NULL,
      APPROVER = 'SUPERVISOR'
    WHEN NOT MATCHED THEN INSERT
      (WORK_ORDER_ID,APPROVAL_LEVEL,APPROVER,APPROVAL_STATUS)
    VALUES
      (P_WORK_ORDER_ID,1,'SUPERVISOR','PENDING');
  END COMPLETE_WORK_ORDER;

  PROCEDURE APPROVE_WORK_ORDER(
    P_WORK_ORDER_ID IN NUMBER,
    P_APPROVER IN VARCHAR2,
    P_DECISION IN VARCHAR2,
    P_REMARKS IN VARCHAR2 DEFAULT NULL
  ) IS
    l_schedule_id NUMBER;
    l_plan_id NUMBER;
    l_machine_id NUMBER;
    l_due_date DATE;
    l_completed_date DATE;
    l_total_down NUMBER;
    l_labour NUMBER;
    l_parts NUMBER;
    l_completed_by VARCHAR2(100);
  BEGIN
    IF P_DECISION NOT IN ('APPROVED','REJECTED') THEN
      RAISE_APPLICATION_ERROR(-20019,'Decision must be APPROVED or REJECTED.');
    END IF;

    SELECT SCHEDULE_ID,PLAN_ID,MACHINE_ID,TARGET_DATE,COMPLETED_DATE_TIME
      INTO l_schedule_id,l_plan_id,l_machine_id,l_due_date,l_completed_date
      FROM MS_PM_WORK_ORDER
     WHERE WORK_ORDER_ID = P_WORK_ORDER_ID
       AND STATUS_CODE = 'PENDING_APPROVAL'
     FOR UPDATE;

    UPDATE MS_PM_APPROVAL
       SET APPROVER = P_APPROVER,
           APPROVAL_STATUS = P_DECISION,
           APPROVAL_DATE = SYSDATE,
           APPROVAL_REMARKS = P_REMARKS
     WHERE WORK_ORDER_ID = P_WORK_ORDER_ID
       AND APPROVAL_LEVEL = 1;

    IF SQL%ROWCOUNT = 0 THEN
      RAISE_APPLICATION_ERROR(-20020,'Pending approval record not found.');
    END IF;

    IF P_DECISION = 'REJECTED' THEN
      UPDATE MS_PM_WORK_ORDER
         SET STATUS_CODE = 'REJECTED',
             COMPLETED_DATE_TIME = NULL
       WHERE WORK_ORDER_ID = P_WORK_ORDER_ID;
      UPDATE MS_PM_SCHEDULE
         SET STATUS_CODE = 'GENERATED'
       WHERE SCHEDULE_ID = l_schedule_id;
    ELSE
      UPDATE MS_PM_WORK_ORDER
         SET STATUS_CODE = 'APPROVED'
       WHERE WORK_ORDER_ID = P_WORK_ORDER_ID;

      UPDATE MS_PM_SCHEDULE
         SET STATUS_CODE = 'COMPLETED'
       WHERE SCHEDULE_ID = l_schedule_id;

      SELECT NVL(SUM(DOWNTIME_MINUTES),0)
        INTO l_total_down
        FROM MS_PM_EXECUTION
       WHERE WORK_ORDER_ID = P_WORK_ORDER_ID;

      SELECT NVL(SUM(HOURS_WORKED),0)
        INTO l_labour
        FROM MS_PM_LABOUR_D
       WHERE WORK_ORDER_ID = P_WORK_ORDER_ID;

      SELECT NVL(SUM(TOTAL_COST),0)
        INTO l_parts
        FROM MS_PM_PARTS_D
       WHERE WORK_ORDER_ID = P_WORK_ORDER_ID;

      SELECT MAX(COMPLETED_BY)
        INTO l_completed_by
        FROM MS_PM_WO_TASK_D
       WHERE WORK_ORDER_ID = P_WORK_ORDER_ID;

      INSERT INTO MS_PM_HISTORY
        (WORK_ORDER_ID,PLAN_ID,MACHINE_ID,SCHEDULE_DATE,COMPLETED_DATE,
         COMPLETED_BY,APPROVED_BY,TOTAL_DOWNTIME,TOTAL_LABOUR_HOURS,
         TOTAL_PARTS_COST,MAINTENANCE_RESULT,REMARKS)
      VALUES
        (P_WORK_ORDER_ID,l_plan_id,l_machine_id,l_due_date,
         NVL(l_completed_date,SYSDATE),l_completed_by,P_APPROVER,
         l_total_down,l_labour,l_parts,'COMPLETED',P_REMARKS);

      UPDATE MS_PM_PLAN_H P
         SET NEXT_DUE_DATE =
           (SELECT MIN(S.DUE_DATE)
              FROM MS_PM_SCHEDULE S
             WHERE S.PLAN_ID = P.PLAN_ID
               AND S.STATUS_CODE IN ('PENDING','OVERDUE'))
       WHERE P.PLAN_ID = l_plan_id;
    END IF;
  END APPROVE_WORK_ORDER;

  PROCEDURE RECEIVE_PART(
    P_ITEM_ID IN NUMBER,
    P_QUANTITY IN NUMBER,
    P_UNIT_COST IN NUMBER,
    P_REFERENCE_NO IN VARCHAR2 DEFAULT NULL,
    P_REMARKS IN VARCHAR2 DEFAULT NULL
  ) IS
  BEGIN
    IF P_QUANTITY <= 0 OR P_UNIT_COST < 0 THEN
      RAISE_APPLICATION_ERROR(-20021,'Receipt quantity must be positive and cost cannot be negative.');
    END IF;

    INSERT INTO MS_PM_STOCK_TXN
      (ITEM_ID,TXN_TYPE,QUANTITY,UNIT_COST,REFERENCE_NO,REMARKS,CREATED_BY)
    VALUES
      (P_ITEM_ID,'RECEIPT',P_QUANTITY,P_UNIT_COST,P_REFERENCE_NO,
       P_REMARKS,MS_CURRENT_USER);
  END RECEIVE_PART;

  PROCEDURE ISSUE_PART(
    P_WORK_ORDER_ID IN NUMBER,
    P_ITEM_ID IN NUMBER,
    P_QUANTITY IN NUMBER,
    P_UNIT_COST IN NUMBER DEFAULT NULL,
    P_REMARKS IN VARCHAR2 DEFAULT NULL
  ) IS
    l_stock NUMBER;
    l_cost NUMBER;
    l_txn_id NUMBER;
  BEGIN
    IF P_QUANTITY <= 0 THEN
      RAISE_APPLICATION_ERROR(-20022,'Issue quantity must be greater than zero.');
    END IF;

    -- Lock item row to serialize simultaneous stock issues for this item.
    SELECT NVL(P_UNIT_COST,0) INTO l_cost
      FROM MS_PM_PART_ITEM
     WHERE ITEM_ID = P_ITEM_ID
       AND ACTIVE_YN = 'Y'
     FOR UPDATE;

    l_stock := GET_STOCK_QTY(P_ITEM_ID);
    IF l_stock < P_QUANTITY THEN
      RAISE_APPLICATION_ERROR(-20023,'Insufficient stock. Available quantity: '||l_stock);
    END IF;

    INSERT INTO MS_PM_STOCK_TXN
      (ITEM_ID,TXN_TYPE,QUANTITY,UNIT_COST,REFERENCE_NO,REMARKS,CREATED_BY)
    VALUES
      (P_ITEM_ID,'ISSUE',P_QUANTITY,l_cost,
       (SELECT WORK_ORDER_NO FROM MS_PM_WORK_ORDER WHERE WORK_ORDER_ID=P_WORK_ORDER_ID),
       P_REMARKS,MS_CURRENT_USER)
    RETURNING STOCK_TXN_ID INTO l_txn_id;

    INSERT INTO MS_PM_PARTS_D
      (WORK_ORDER_ID,ITEM_ID,STOCK_TXN_ID,QUANTITY,UNIT_COST,TOTAL_COST,
       REMARKS,CREATED_BY)
    VALUES
      (P_WORK_ORDER_ID,P_ITEM_ID,l_txn_id,P_QUANTITY,l_cost,
       P_QUANTITY*l_cost,P_REMARKS,MS_CURRENT_USER);
  END ISSUE_PART;

  PROCEDURE DAILY_JOB(P_SCHEDULE_HORIZON_DAYS IN NUMBER DEFAULT 90) IS
  BEGIN
    IF P_SCHEDULE_HORIZON_DAYS < 1 OR P_SCHEDULE_HORIZON_DAYS > 730 THEN
      RAISE_APPLICATION_ERROR(-20024,'Schedule horizon must be between 1 and 730 days.');
    END IF;

    FOR p IN (
      SELECT PLAN_ID
        FROM MS_PM_PLAN_H
       WHERE STATUS_CODE = 'ACTIVE'
         AND ACTIVE_YN = 'Y'
         AND (END_DATE IS NULL OR END_DATE >= TRUNC(SYSDATE))
    ) LOOP
      GENERATE_SCHEDULE(p.PLAN_ID,TRUNC(SYSDATE)+P_SCHEDULE_HORIZON_DAYS);
    END LOOP;

    UPDATE MS_PM_SCHEDULE
       SET STATUS_CODE = 'OVERDUE'
     WHERE STATUS_CODE = 'PENDING'
       AND DUE_DATE < TRUNC(SYSDATE);

    GENERATE_WORK_ORDERS(TRUNC(SYSDATE));

    UPDATE MS_PM_PLAN_H P
       SET NEXT_DUE_DATE =
         (SELECT MIN(S.DUE_DATE)
            FROM MS_PM_SCHEDULE S
           WHERE S.PLAN_ID = P.PLAN_ID
             AND S.STATUS_CODE IN ('PENDING','OVERDUE'))
     WHERE P.STATUS_CODE = 'ACTIVE'
       AND P.ACTIVE_YN = 'Y';
  END DAILY_JOB;

END MS_PM_PKG;
