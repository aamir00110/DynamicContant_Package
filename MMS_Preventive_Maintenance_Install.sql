CREATE TABLE MS_PM_FREQUENCY (
  FREQUENCY_ID       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  FREQUENCY_CODE     VARCHAR2(30) NOT NULL,
  FREQUENCY_NAME     VARCHAR2(100) NOT NULL,
  INTERVAL_DAYS      NUMBER,
  INTERVAL_MONTHS    NUMBER,
  ACTIVE_YN          CHAR(1) DEFAULT 'Y' NOT NULL,
  CREATED_BY         VARCHAR2(100),
  CREATED_DATE       DATE DEFAULT SYSDATE NOT NULL,
  UPDATED_BY         VARCHAR2(100),
  UPDATED_DATE       DATE,
  CONSTRAINT PK_MS_PM_FREQUENCY PRIMARY KEY (FREQUENCY_ID),
  CONSTRAINT UK_MS_PM_FREQ_CODE UNIQUE (FREQUENCY_CODE),
  CONSTRAINT CK_MS_PM_FREQ_ACTIVE CHECK (ACTIVE_YN IN ('Y','N')),
  CONSTRAINT CK_MS_PM_FREQ_INTERVAL CHECK (
    (FREQUENCY_CODE IN ('DAILY','WEEKLY','BIWEEKLY','CUSTOM')
      AND INTERVAL_DAYS IS NOT NULL AND INTERVAL_DAYS > 0
      AND INTERVAL_MONTHS IS NULL)
    OR
    (FREQUENCY_CODE IN ('MONTHLY','QUARTERLY','HALF_YEARLY','YEARLY')
      AND INTERVAL_MONTHS IS NOT NULL AND INTERVAL_MONTHS > 0
      AND INTERVAL_DAYS IS NULL)
