DECLARE
  PROCEDURE assert_table(p_name VARCHAR2) IS
    l_count NUMBER;
  BEGIN
    SELECT COUNT(*) INTO l_count
      FROM USER_TABLES
     WHERE TABLE_NAME = UPPER(p_name);
    IF l_count = 0 THEN
      RAISE_APPLICATION_ERROR(-20001,
        'Required existing table not found: ' || p_name);
    END IF;
  END;
BEGIN
  assert_table('EM_HALLS');
  assert_table('EM_LINES');
  assert_table('EM_MACHINES');
  assert_table('EM_MACHINE_FAULTS');
  DBMS_OUTPUT.PUT_LINE('Existing MMS master tables verified.');
END;
/

